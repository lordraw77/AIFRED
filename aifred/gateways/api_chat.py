"""Web chat endpoint: ``POST /api/chat`` streams the agent's events as Server-Sent Events (spec 10.4).

The dashboard (or any admin client) sends ``{"session_id": "web:<uuid>", "message": "..."}``. Slash
commands are handled here too and answered with a single ``command`` event.
"""

from __future__ import annotations

import asyncio
import json
import re
from collections.abc import AsyncIterator
from typing import Any

from fastapi import APIRouter, HTTPException, status
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field

from aifred.commands import Commands, Context
from aifred.gateways.api import AdminDep, ServicesDep

router = APIRouter()

SESSION_RE = re.compile(r"^web:[A-Za-z0-9._-]{1,64}$")
KEEPALIVE_SECONDS = 15.0
_END = object()


class ChatIn(BaseModel):
    """A chat message."""

    session_id: str = Field(description="web:<uuid>, generated by the client")
    message: str = Field(min_length=1, max_length=100_000)


def _event(data: dict[str, Any]) -> bytes:
    return b"data: " + json.dumps(data, ensure_ascii=False).encode() + b"\n\n"


async def _pump(source: AsyncIterator[Any], queue: asyncio.Queue[Any]) -> None:
    try:
        async for item in source:
            await queue.put(item)
    finally:
        await queue.put(_END)


@router.post("/api/chat", response_model=None)
async def chat(body: ChatIn, _: AdminDep, services: ServicesDep) -> StreamingResponse:
    """Run a turn (or a slash command) and stream the events."""
    if not SESSION_RE.match(body.session_id):
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "session_id must look like web:<uuid> (letters, digits, '.', '_' and '-')")
    if not body.message.strip():
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "the message is empty")
    await asyncio.to_thread(services.config.reload)

    reply = await Commands(services).run(body.message, Context(body.session_id, "web", False))
    if reply is not None:
        async def command_stream() -> AsyncIterator[bytes]:
            yield _event({"type": "command", "text": reply.text, "session_id": reply.session_id})
        return StreamingResponse(command_stream(), media_type="text/event-stream", headers={"Cache-Control": "no-cache"})

    queue: asyncio.Queue[Any] = asyncio.Queue()
    task = asyncio.create_task(_pump(services.agent.run(body.session_id, body.message, "web"), queue))

    async def stream() -> AsyncIterator[bytes]:
        try:
            while True:
                try:
                    item = await asyncio.wait_for(queue.get(), KEEPALIVE_SECONDS)
                except asyncio.TimeoutError:
                    yield b": keep-alive\n\n"
                    continue
                if item is _END:
                    return
                yield _event(item.to_dict())
        finally:
            task.cancel()  # the browser went away: stop the turn and release the session

    return StreamingResponse(stream(), media_type="text/event-stream", headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"})
